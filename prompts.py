"""评论挖掘用的提示词。集中管理,方便后续调整。"""

BATCH_ANALYSIS_SYSTEM = (
    "你是一名资深跨境电商选品分析师,擅长从用户评论中挖掘选品价值。\n"
    "你的任务:分析一批商品评论,提取结构化洞察。只输出 JSON,不要输出任何其他文字或解释。"
)


def batch_analysis_prompt(reviews_text: str) -> str:
    """生成「分批分析」的用户提示词。"""
    return f"""请分析下面这批商品评论,提取以下四类信息(用中文,每条简洁具体):

1. positives: 用户反复提到的优点 / 卖点
2. pain_points: 用户抱怨的问题 / 痛点
3. purchase_motives: 用户的购买动机和使用场景
4. competitor_mentions: 用户提到的其他品牌或竞品对比

评论列表:
{reviews_text}

严格输出如下 JSON(数组;若某一项没有内容,则输出空数组):
{{"positives": ["..."], "pain_points": ["..."], "purchase_motives": ["..."], "competitor_mentions": ["..."]}}"""


SUMMARY_SYSTEM = (
    "你是资深跨境电商选品分析师。根据分批评论分析的结果,生成一份完整的选品分析报告。"
)


def summary_prompt(aggregated: str) -> str:
    """生成「汇总报告」的用户提示词。"""
    return f"""根据以下分批评论分析的结果,生成一份专业、详尽的选品分析报告(Markdown 格式,用中文)。

标题格式:「# 选品分析报告:产品名称」,产品名从评论推断(有品牌/型号就写,否则写品类名,如「笔记本电脑」)。报告要具体有洞察,善用表格和数据支撑,避免空泛套话。

正文包含:

1. **总体口碑概览** — 用户整体满意度和主要印象
2. **核心卖点** — 用户最在意的优点,按重要性排序
3. **主要痛点** — 用户最不满的问题,按频次排序
4. **改进机会** — 改善哪些点能显著提升评分
5. **购买动机与目标人群** — 用户为什么买、哪些人在买
6. **竞品线索** — 用户提到的竞品和对比
7. **选品结论** — 这个产品值不值得做、要注意什么、差异化建议

分批分析结果:
{aggregated}"""


COMPARISON_SYSTEM = (
    "你是资深跨境电商选品分析师,擅长横向对比多个竞品并给出选品建议。"
)


def comparison_prompt(aggregated: str) -> str:
    """生成「竞品对比」的用户提示词。"""
    return f"""根据以下多个竞品的评论分析结果,生成一份竞品对比分析报告(Markdown 格式,用中文),包含:

1. **竞品概览对比表** — 每个竞品的评论数、平均评分、核心卖点、主要痛点(用表格)
2. **卖点横向对比** — 哪些是共性卖点(大家都有的),哪些是差异化卖点(某家独有或更突出)
3. **痛点横向对比** — 哪些是行业通病,哪些是某个竞品独有或更严重
4. **差异化切入机会** — 相对弱势的竞品、可以切入的市场空白点
5. **选品建议** — 推荐哪个方向值得做、理由是什么、要注意什么风险

各竞品分析结果:
{aggregated}"""


LISTING_SYSTEM = (
    "你是资深亚马逊 Listing 优化专家,精通平台合规规则和高转化文案写法。\n"
    "你写出的 Listing 必须同时满足:合规(不碰红线)、准确(参数可核验)、完整(字段齐全)、"
    "可搜(关键词结构合理)、可读(利益前置、有证据)。"
)


def listing_prompt(
    sell_points: str, product_category: str = "", violations: str = ""
) -> str:
    """生成「Listing 文案」的用户提示词(含硬性红线 + 写法规范)。

    violations 非空时追加「上一版被确定性闸门拦下」的修正指令 —— 这是重写闭环的输入。
    """
    fix_block = ""
    if violations:
        fix_block = f"""

## ⚠️ 上一版被确定性合规闸门拦下,必须逐条修正后重新输出
{violations}

要求:输出**完整** Listing(不要只给修改片段),且不得再命中上述任何一项。"""
    return f"""根据以下产品卖点,生成一份符合亚马逊规范的完整 Listing(中文)。

## 硬性红线(违反任一 = 不合格)
- 禁止绝对化用语:「最好」「第一」「全网最低」「顶级」「唯一」「爆款」「热销」
- 禁止促销信息:价格、「买2送1」「包邮」「限时折扣」
- 禁止主观夸赞:「Best Seller」「Hot Item」「Top Rated」
- 禁止承诺性表述:「终身保修」「100% 有效」「保证」
- 禁止医疗/功效声明:「治疗」「消炎」「降血压」
- 禁止联系方式、外链、二维码;禁止他人品牌词;禁止未授权认证

## 格式与准确性
- 标题 ≤200 字符;不用全大写;不用 ! ? $ emoji 等特殊符号;数字用阿拉伯数字;每个实词首字母大写
- 参数带明确单位(500ml、320g、25×8×8cm),不写「大容量」「很轻」等模糊词
- 量词有基准(如「95℃ 起始、室温 20℃ 条件下保温 24 小时」);不留歧义;不遗漏风险信息

## 写法(按「利益 → 特性 → 证据」三层)
- 每个卖点先讲利益(用户得到什么),再讲特性(凭什么),最后给可核验证据
- 五点分工(不要五点都写质量好):①核心利益 ②差异化功能 ③使用场景 ④材质/参数可信度 ⑤安心售后(只客观陈述随附物品,不承诺保修)
- 首屏原则:最关键利益放前 80 字符

## 输出
只输出下面五项。**不要**输出合规自检、红线对照表、修改说明或任何解释性文字 ——
那些内容会引用到违禁词本身,反而触发合规闸门。
1. 标题(核心词前置 + 属性词 + 场景词 + 规格词,一词只出现一次,不堆砌)
2. 五点描述(5 条,按上述分工)
3. 详情页描述(2~3 段)
4. 规格参数表(容量/尺寸/材质/重量等,带单位)
5. 关键词建议(5~10 个)

品类:{product_category or '未知'}

产品卖点:
{sell_points}{fix_block}"""


COMPLIANCE_SYSTEM = (
    "你是亚马逊 Listing 合规审查专家,按「一票否决清单」逐条审查文案。"
)


def compliance_prompt(listing_text: str) -> str:
    """生成「合规审查」的用户提示词(一票否决清单)。"""
    return f"""按以下「一票否决清单」逐条检查这份 Listing,输出审查结果(中文)。

## 一票否决项(任一命中 = 不合格)
1. 绝对化用语:最好 / 第一 / 唯一 / 顶级 / 国家级 / 全网最低 / 销量冠军
2. 促销信息:价格 / 买2送1 / 包邮 / 限时折扣
3. 主观夸赞:Best Seller / Hot Item / Top Rated / 爆款 / 热销
4. 承诺性表述:终身保修 / 100% 有效 / 无效退款 / 保证
5. 医疗功效声明:治疗 / 消炎 / 降血压 / 抗癌
6. 联系方式与外链:电话 / 邮箱 / URL / 微信 / 二维码
7. 他人品牌词、竞品商标
8. 未授权认证(FDA / CE / 3C 等)

## 其他检查项
- 参数是否有单位、可核验、无歧义
- 标题格式(≤200 字符、无特殊符号/emoji、无全大写)
- 关键词是否堆砌重复;必填字段是否齐全

对每处问题:指出「位置 + 问题 + 修改建议」。若无问题,明确说「未发现违规」。

Listing 文案:
{listing_text}"""


